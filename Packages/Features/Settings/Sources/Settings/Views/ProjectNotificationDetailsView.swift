import Foundation
import SwiftUI
import VikuDesignSystem
import VikunjaCore
import VikuUI

/// Saved registration information remains readable offline. Other webhooks need
/// the server; failed refreshes preserve the last result and offer a retry.
struct ProjectNotificationDetailsView: View {
    let viewModel: NotificationsViewModel
    let project: Project

    @Environment(\.vikuPalette) private var palette

    private var loadState: ScreenLoadState<[Webhook]> {
        viewModel.otherWebhookLoadState(for: project)
    }

    private var maskedTarget: String {
        guard let url = viewModel.relayTargetURL else { return "—" }
        let host = url.host ?? url.absoluteString
        let last = url.lastPathComponent
        return last.count > 4 ? "\(host)/••••\(last.suffix(4))" : host
    }

    var body: some View {
        ScrollView {
            VStack(alignment: .leading, spacing: 0) {
                sectionHeader(String(localized: "Technical Details", bundle: .module))
                VStack(alignment: .leading, spacing: VikuSpacing.md) {
                    infoRow(
                        title: String(localized: "Destination", bundle: .module),
                        value: maskedTarget,
                        monospaced: true,
                    )
                    infoRow(
                        title: String(localized: "Signature", bundle: .module),
                        value: viewModel.hasWebhookSigningSecret
                            ? String(localized: "HMAC secret generated by Viku", bundle: .module)
                            : String(localized: "Not configured", bundle: .module),
                    )
                    infoRow(
                        title: String(localized: "Status", bundle: .module),
                        value: viewModel.projectNotificationPreset(for: project) == .disabled
                            ? String(localized: "Disabled", bundle: .module)
                            : String(localized: "Configured", bundle: .module),
                    )
                }
                .frame(maxWidth: .infinity, alignment: .leading)
                .padding(.vertical, VikuSpacing.sm)
                .vikuCardRow(index: 0, count: 1)

                sectionHeader(String(localized: "Other Webhooks on This Project", bundle: .module))
                otherWebhooksSection
            }
            .padding(.bottom, VikuSpacing.xxl)
        }
        .background(palette.pageBackground)
        .navigationTitle(Text("More Details", bundle: .module))
        #if os(iOS)
        .navigationBarTitleDisplayMode(.inline)
        #endif
        .task(id: project.id) { await viewModel.loadOtherWebhooks(for: project) }
    }

    private var otherWebhooksSection: some View {
        VStack(alignment: .leading, spacing: 0) {
            let webhooks = loadState.value ?? viewModel.cachedOtherWebhooks(for: project)
            ForEach(Array(webhooks.enumerated()), id: \.element.id) { index, webhook in
                HStack(alignment: .top, spacing: VikuSpacing.sm) {
                    Image(systemName: "link")
                        .font(VikuFont.footnote)
                        .foregroundStyle(palette.textTertiary)
                    VStack(alignment: .leading, spacing: VikuSpacing.xxs) {
                        Text(verbatim: webhook.targetURL.absoluteString)
                            .font(VikuFont.footnote.monospaced())
                            .foregroundStyle(palette.textPrimary)
                            .textSelection(.enabled)
                        Text(
                            "\(webhook.events.count) events · created outside Viku · read-only",
                            bundle: .module,
                        )
                        .font(VikuFont.caption)
                        .foregroundStyle(palette.textTertiary)
                    }
                }
                .frame(maxWidth: .infinity, alignment: .leading)
                .padding(.vertical, VikuSpacing.xs)
                .vikuCardRow(index: index, count: webhooks.count)
            }
            if loadState.isLoaded, webhooks.isEmpty {
                Text("No other webhooks on this project.", bundle: .module)
                    .font(VikuFont.footnote)
                    .foregroundStyle(palette.textSecondary)
                    .frame(maxWidth: .infinity, alignment: .leading)
                    .padding(.vertical, VikuSpacing.xs)
                    .vikuCardRow(index: 0, count: 1)
            }
            if let message = loadState.failureMessage {
                VikuStatusView(
                    systemImage: "exclamationmark.triangle.fill",
                    title: String(localized: "Couldn't load other webhooks", bundle: .module),
                    message: message,
                ) {
                    Task { await viewModel.loadOtherWebhooks(for: project) }
                }
                .padding(.horizontal, VikuSpacing.md)
            }
            NotificationProgressView(
                isActive: loadState.isLoading,
                title: String(localized: "Loading other webhooks…", bundle: .module),
            )
            .padding(.horizontal, VikuSpacing.md)
        }
    }

    private func sectionHeader(_ title: String) -> some View {
        Text(verbatim: title)
            .vikuSectionHeader()
            .padding(.horizontal, VikuSpacing.md)
            .padding(.top, VikuSpacing.md + VikuSpacing.xs)
            .padding(.bottom, VikuSpacing.sm)
    }

    private func infoRow(title: String, value: String, monospaced: Bool = false) -> some View {
        VStack(alignment: .leading, spacing: VikuSpacing.xxs) {
            Text(verbatim: title)
                .font(VikuFont.caption)
                .foregroundStyle(palette.textTertiary)
            Text(verbatim: value)
                .font(monospaced ? VikuFont.footnote.monospaced() : VikuFont.footnote)
                .foregroundStyle(palette.textPrimary)
                .textSelection(.enabled)
        }
    }
}
